use("University")

db.studentdb.aggregate(
    [
        {
            $match:{
                course:"BCA"
            }
        }
        ,{
            $project:{
                name:1,
                section:1,
                marks:1,
                semester:1,
                _id:0
            }
        }
        ,{
            $group:{
                _id:"$semester",
                totalMarks:{$sum:"$marks"},
                averageMarks:{$avg:"$marks"},
                maxMarks:{$max:"$marks"},
                minMarks:{$min:"$marks"},
                totalStudents:{$sum:1}

            }
        }
    ]
)